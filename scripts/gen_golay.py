"""Write InfinityMachineOutput/Golay/Circuit.lean from data/golay/evo_44_depth6_cyclic.json."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / "data/golay/evo_44_depth6_cyclic.json").read_text())
names = {"H": "h", "S": "s", "SDG": "sdg", "X": "x", "Y": "y", "Z": "z", "CZ": "cz", "CX": "cx"}
gates = [f".{names[g[0]]} " + " ".join(str(q) for q in g[1:]) for g in data["gates"]]
lines = ",\n  ".join(", ".join(gates[i:i + 8]) for i in range(0, len(gates), 8))
out = f"""import InfinityMachineOutput.Golay.Basic

/-! Generated by `scripts/gen_golay.py` from `data/golay/evo_44_depth6_cyclic.json`
(Zenodo 10.5281/zenodo.23509367). Gates are applied left to right to `|0⟩^⊗23`. -/

namespace Golay

def circuit : List Gate := [
  {lines}]

end Golay
"""
(ROOT / "InfinityMachineOutput/Golay/Circuit.lean").write_text(out, encoding="utf-8")
print(len(gates), "gates")
