"""Write InfinityMachineOutput/StabRank/Data.lean from data/stabrank/T7_rank10.json.

The exact coefficients are recomputed with the deposited exact Q(zeta_8) solver (scripts/stabrank_ref.py) and
scaled by their common denominator so that the Lean statement is an identity in Z[zeta_8]."""
import json, math, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import stabrank_ref as sr

d = json.loads((ROOT / "data/stabrank/T7_rank10.json").read_text())
m, forms = d["m"], d["states"]
cols = [sr.form_exact_column(f) for f in forms]
cs = sr.exact_in_span(cols, sr.exact_target(m))
den = math.lcm(*[x.denominator for c in cs for x in c.c])
ints = lambda bits: int("".join(map(str, bits)), 2) if bits else 0
L = ["import InfinityMachineOutput.StabRank.Basic", "",
     "/-! Generated by `scripts/gen_stabrank.py` from `data/stabrank/T7_rank10.json` (Zenodo 10.5281/zenodo.23525753).",
     "Bit strings are read most-significant-first, as in the deposited checker. -/", "", "namespace StabRank", "",
     f"def m : Nat := {m}", f"def denom : Int := {den}", "", "def forms : List Form := ["]
for i, f in enumerate(forms):
    B = "[" + ", ".join("[" + ", ".join(str(int(v)) for v in r) + "]" for r in f["B"]) + "]"
    L.append(f"  {{ x0 := {ints(f['x0'])}, G := [{', '.join(str(ints(g)) for g in f['G'])}], "
             f"a := [{', '.join(str(int(v) % 4) for v in f['a'])}], B := {B} }}" + ("," if i < len(forms) - 1 else "]"))
L += ["", "/-- `denom · cⱼ` for the exact coefficients `cⱼ ∈ ℚ(ζ₈)`. -/", "def coeffs : List Z8 := ["]
for i, c in enumerate(cs):
    v = [x * den for x in c.c]
    assert all(x.denominator == 1 for x in v)
    L.append(f"  ⟨{', '.join(str(int(x)) for x in v)}⟩" + ("," if i < len(cs) - 1 else "]"))
L += ["", "end StabRank", ""]
(ROOT / "InfinityMachineOutput/StabRank/Data.lean").write_text("\n".join(L), encoding="utf-8")
print("m", m, "states", len(forms), "denominator", den, [str(c) for c in cs])
