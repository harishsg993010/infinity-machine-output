"""Write InfinityMachineOutput/Sabre/Data.lean from data/sabre/benchmarks/*.qasm and data/sabre/routings.json.

Encodings (parsed in Lean):
  circuit string: gates separated by ';', each gate the comma-separated logical qubits it acts on (file order);
  ops string: space-separated tokens, a gate index `g` or a swap `p-q` on physical qubits."""
import json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
routes = json.loads((ROOT / "data/sabre/routings.json").read_text())["circuits"]
refs = json.loads((ROOT / "data/sabre/refs.json").read_text())
L = ["import InfinityMachineOutput.Sabre.Basic", "",
     "/-! Generated by `scripts/gen_sabre.py` from the 26 SABRE benchmark circuits and the routings deposited at",
     "Zenodo 10.5281/zenodo.23651580. -/", "", "namespace Sabre", "", "def instances : List Instance := ["]
items = []
for name in refs:
    gates, n = [], 0
    for raw in (ROOT / f"data/sabre/benchmarks/{name}.qasm").read_text().splitlines():
        line = raw.split("//")[0].strip()
        if not line or line.startswith(("OPENQASM", "include", "creg", "barrier", "measure")):
            continue
        if line.startswith("qreg"):
            n = int(re.search(r"\[(\d+)\]", line).group(1)); continue
        qs = re.findall(r"q\[(\d+)\]", line)
        assert 1 <= len(qs) <= 2, line
        gates.append(",".join(qs))
    n = max(n, 1 + max(int(q) for g in gates for q in g.split(",")))
    r = routes[name]
    ops = " ".join(f"{o[1]}-{o[2]}" if isinstance(o, list) else str(o) for o in r["ops"])
    items.append(f'  {{ name := "{name}", n := {n}, mapping := {r["mapping"]}, sabreRef := {refs[name]},\n'
                 f'    gates := "{";".join(gates)}",\n    ops := "{ops}" }}')
L.append(",\n".join(items) + "]")
L += ["", "end Sabre", ""]
(ROOT / "InfinityMachineOutput/Sabre/Data.lean").write_text("\n".join(L), encoding="utf-8")
print(len(items), "instances")
